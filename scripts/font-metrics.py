"""Write src/core/fontMetrics.ts: character widths for the title fonts.

Run with: python3 scripts/font-metrics.py   (needs: pip install fonttools brotli)

Widths are read from the same font files the app uses, at weights 300 to 600,
so title shapes can be sized the same way in the browser and in tests.
"""
import io
import json
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = {
    'Manrope': ROOT / 'node_modules/@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2',
    'Open Sans': ROOT / 'node_modules/@fontsource-variable/open-sans/files/open-sans-latin-wght-normal.woff2',
}
WEIGHTS = [300, 400, 500, 600]
CHARS = ''.join(chr(c) for c in range(32, 127)) + '’‘“”–—éèàçüöäñ×·'

out = {}
for family, path in FONTS.items():
    base = TTFont(path)
    upm = base['head'].unitsPerEm
    os2 = base['OS/2']
    entry = {
        'ascender': round(base['hhea'].ascent / upm, 4),
        'descender': round(base['hhea'].descent / upm, 4),
        'capHeight': round(getattr(os2, 'sCapHeight', 700) / upm, 4),
        'xHeight': round(getattr(os2, 'sxHeight', 500) / upm, 4),
        'widths': {},
    }
    for w in WEIGHTS:
        font = instantiateVariableFont(TTFont(path), {'wght': w})
        cmap = font.getBestCmap()
        hmtx = font['hmtx']
        widths = []
        for ch in CHARS:
            glyph = cmap.get(ord(ch))
            widths.append(round(hmtx[glyph][0] / upm, 4) if glyph else None)
        entry['widths'][w] = widths
    out[family] = entry

ts = (
    '// Generated by scripts/font-metrics.py. Do not edit by hand.\n'
    '// Character widths (in ems) for the title fonts at weights 300 to 600.\n\n'
    f'export const METRIC_CHARS = {json.dumps(CHARS, ensure_ascii=False)};\n\n'
    f'export const FONT_METRICS = {json.dumps(out, ensure_ascii=False)} as const;\n'
)
(ROOT / 'src/core/fontMetrics.ts').write_text(ts, encoding='utf-8')
print('wrote src/core/fontMetrics.ts')
